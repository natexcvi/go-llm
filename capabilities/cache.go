package capabilities

import (
	"context"
	"errors"
	"fmt"
	"slices"
	"strings"
	"time"

	h "github.com/natexcvi/go-llm"
)

// LabelCrossModelHistory identifies earlier assistant responses from a different
// model. Install it after ModelRouter to label for the selected model.
func LabelCrossModelHistory() h.Capability {
	return func(ctx context.Context, r *h.Run) error {
		return before(func(_ context.Context, q *h.Request, _ h.Usage) error {
			current, ok := r.Model.(h.NamedModel)
			if !ok {
				return nil
			}
			var previous []string
			for _, m := range q.Messages {
				if m.Role == h.Assistant && m.Model != "" && m.Model != current.ModelName() && !slices.Contains(previous, m.Model) {
					previous = append(previous, m.Model)
				}
			}
			if len(previous) > 0 {
				note := fmt.Sprintf("Earlier assistant turns in this conversation were generated by %s. The current model is %s.", strings.Join(previous, ", "), current.ModelName())
				q.Messages = append([]h.Message{{Role: h.System, Text: note}}, q.Messages...)
			}
			return nil
		})(ctx, r)
	}
}

type CacheWarning struct {
	Model          string
	Previous, Read int
}
type cacheMark struct {
	Prefix   int
	Observed time.Time
	Warned   bool
}

// WarnOnCacheBusts observes cache counters from the provider. A growing
// prefix re-arms warnings. Retention suppresses expected misses after expiry.
func WarnOnCacheBusts(minMissed int, minRatio float64, retention time.Duration, notify func(CacheWarning)) h.Capability {
	return func(ctx context.Context, r *h.Run) error {
		if minMissed < 1 || minRatio < 0 || minRatio > 1 || retention < 0 || notify == nil {
			return errors.New("invalid cache warning configuration")
		}
		marks := map[string]cacheMark{}
		if err := h.BindState(r, "cache_marks", &marks); err != nil {
			return err
		}
		r.AfterResponse = append(r.AfterResponse, func(_ context.Context, resp h.Response) error {
			old := marks[resp.Model]
			now := time.Now()
			missed := old.Prefix - resp.CacheReadTokens
			collapse := old.Prefix > 0 && missed >= minMissed && float64(missed)/float64(old.Prefix) >= minRatio
			expired := retention > 0 && now.Sub(old.Observed) > retention
			if collapse && !expired && !old.Warned {
				notify(CacheWarning{resp.Model, old.Prefix, resp.CacheReadTokens})
			}
			marks[resp.Model] = cacheMark{Prefix: resp.CacheReadTokens + resp.CacheWriteTokens, Observed: now, Warned: collapse && !expired}
			return nil
		})
		return nil
	}
}
